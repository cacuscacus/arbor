#!/usr/bin/env bash
# Builds a deterministic, throwaway file tree for manual Arbor testing:
#   ./scripts/make-test-fixtures.sh [target-dir]
# Default target: <repo>/test_file_structure (git-ignored).
#
# The tree is recreated from scratch on every run. It stays inside the repo so
# browsing / searching / mutating it never touches real user files.
set -euo pipefail

ROOT="$(cd "$(dirname "$0")/.." && pwd)"
TARGET="${1:-$ROOT/test_file_structure}"

# Safety: only ever delete a directory named test_file_structure under ROOT
# (or an explicitly provided, non-root path that already looks like our fixture).
TARGET_ABS="$(cd "$(dirname "$TARGET")" 2>/dev/null && pwd)/$(basename "$TARGET")" || true
case "$TARGET_ABS" in
  "$ROOT/test_file_structure"|"$ROOT"/*/test_file_structure) ;;
  *)
    echo "Refusing to wipe unexpected target: $TARGET_ABS" >&2
    exit 1
    ;;
esac
if [ "$TARGET_ABS" = "/" ] || [ "$TARGET_ABS" = "$HOME" ]; then
  echo "Refusing to wipe $TARGET_ABS" >&2
  exit 1
fi

# A previous run leaves a deliberately unreadable directory behind; restore
# owner permissions before wiping so the fixture can always be regenerated.
if [ -d "$TARGET_ABS" ]; then
  chmod -R u+rwX "$TARGET_ABS" 2>/dev/null || true
fi
rm -rf "$TARGET_ABS"
mkdir -p "$TARGET_ABS"

python3 - "$TARGET_ABS" <<'PY'
import base64
import os
import random
import struct
import sys
import time
import zlib

root = sys.argv[1]
random.seed(20260815)


def path(*parts):
    return os.path.join(root, *parts)


def write(rel, data=b"", mode=None):
    full = path(rel)
    os.makedirs(os.path.dirname(full), exist_ok=True)
    with open(full, "wb") as fh:
        fh.write(data if isinstance(data, bytes) else data.encode())
    if mode is not None:
        os.chmod(full, mode)
    return full


def touch(rel, when=None):
    return write(rel, b"", when)


def png(width, height, rgb):
    """Minimal valid PNG (no external deps)."""
    def chunk(kind, payload):
        return struct.pack(">I", len(payload)) + kind + payload + struct.pack(
            ">I", zlib.crc32(kind + payload) & 0xFFFFFFFF
        )

    ihdr = struct.pack(">IIBBBBB", width, height, 8, 2, 0, 0, 0)
    rows = b"".join(b"\x00" + bytes(rgb) * width for _ in range(height))
    return (
        b"\x89PNG\r\n\x1a\n"
        + chunk(b"IHDR", ihdr)
        + chunk(b"IDAT", zlib.compress(rows, 9))
        + chunk(b"IEND", b"")
    )


